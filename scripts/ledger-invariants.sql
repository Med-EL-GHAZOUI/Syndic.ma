-- Ledger & integrity invariants. Returns one row per VIOLATION; an empty result means healthy.
-- Run against production after a restore, a migration, or on a schedule:
--   psql -v ON_ERROR_STOP=1 -tA -f scripts/ledger-invariants.sql
-- Every check mirrors a rule enforced by the application and covered by the e2e tests.

-- I1/I4: no charge is allocated beyond its amount (recorded payments only)
SELECT 'charge over-allocated' AS violation, c.id::text AS ref
  FROM charges c
  JOIN allocations a ON a.charge_id = c.id
  JOIN payments p ON p.id = a.payment_id
 WHERE p.status = 'recorded'
 GROUP BY c.id, c.amount
HAVING SUM(ROUND(a.amount * 100)) > ROUND(c.amount * 100)

UNION ALL
-- I4: a recorded/reversed payment is fully allocated (allocated == amount)
SELECT 'payment not fully allocated', p.id::text
  FROM payments p
  LEFT JOIN allocations a ON a.payment_id = p.id
 WHERE p.status IN ('recorded', 'reversed')
 GROUP BY p.id, p.amount
HAVING COALESCE(SUM(ROUND(a.amount * 100)), 0) <> ROUND(p.amount * 100)

UNION ALL
-- pending / rejected payments must have no financial effect
SELECT 'allocation on non-confirmed payment', p.id::text
  FROM allocations a JOIN payments p ON p.id = a.payment_id
 WHERE p.status IN ('pending', 'rejected')
 GROUP BY p.id

UNION ALL
-- I5: receipt numbers unique per organization
SELECT 'duplicate receipt number', org_id::text || '/' || receipt_no
  FROM payments WHERE receipt_no IS NOT NULL
 GROUP BY org_id, receipt_no HAVING COUNT(*) > 1

UNION ALL
-- I5: receipt numbering is gap-free per organization/year (counter == highest number == count)
SELECT 'receipt numbering gap', x.org_id::text || '/' || x.yr
  FROM (SELECT org_id, split_part(receipt_no, '-', 2) AS yr, COUNT(*) AS n, MAX(split_part(receipt_no, '-', 3)::int) AS mx
          FROM payments WHERE receipt_no IS NOT NULL GROUP BY org_id, split_part(receipt_no, '-', 2)) x
 WHERE x.n <> x.mx

UNION ALL
-- I2: charges generated by an issued call sum exactly to the call total (tantiemes basis)
SELECT 'call total mismatch', k.id::text
  FROM calls_for_funds k
  JOIN charges c ON c.call_id = k.id
 WHERE k.basis = 'tantiemes' AND k.status <> 'draft'
 GROUP BY k.id, k.total_amount
HAVING SUM(ROUND(c.amount * 100)) <> ROUND(k.total_amount * 100)

UNION ALL
-- tantièmes of a residence add up to 1000
SELECT 'tantiemes do not sum to 1000', residence_id::text
  FROM units GROUP BY residence_id HAVING SUM(tantiemes) <> 1000

UNION ALL
-- every tenant row belongs to an existing organization
SELECT 'orphan residence (no organization)', r.id::text
  FROM residences r LEFT JOIN organizations o ON o.id = r.org_id WHERE o.id IS NULL

UNION ALL
-- cross-tenant leakage: a payment's unit must belong to the same organization
SELECT 'payment/unit organization mismatch', p.id::text
  FROM payments p JOIN units u ON u.id = p.unit_id WHERE u.org_id <> p.org_id

UNION ALL
SELECT 'charge/unit organization mismatch', c.id::text
  FROM charges c JOIN units u ON u.id = c.unit_id WHERE u.org_id <> c.org_id

UNION ALL
-- reconciliation: verified <=> matched to exactly one bank line
SELECT 'verified payment without a matched bank line', p.id::text
  FROM payments p
 WHERE p.verified AND NOT EXISTS (SELECT 1 FROM bank_lines b WHERE b.payment_id = p.id AND b.status = 'matched')

UNION ALL
SELECT 'matched bank line on a non-verified payment', b.id::text
  FROM bank_lines b JOIN payments p ON p.id = b.payment_id WHERE b.status = 'matched' AND NOT p.verified

UNION ALL
SELECT 'payment matched by several bank lines', b.payment_id::text
  FROM bank_lines b WHERE b.status = 'matched' GROUP BY b.payment_id HAVING COUNT(*) > 1

UNION ALL
-- database-level protections must still exist (a bad migration once dropped them)
SELECT 'missing CHECK constraints (expected >= 18)', COUNT(*)::text
  FROM pg_constraint WHERE contype = 'c' AND conname LIKE 'chk\_%'
HAVING COUNT(*) < 18

UNION ALL
SELECT 'missing trigger ' || t.name, ''
  FROM (VALUES ('audit_logs_append_only'), ('audit_logs_no_truncate'), ('payments_no_delete'), ('assemblies_no_delete_held'), ('period_closures_append_only')) AS t(name)
 WHERE NOT EXISTS (SELECT 1 FROM pg_trigger g WHERE g.tgname = t.name AND NOT g.tgisinternal);
