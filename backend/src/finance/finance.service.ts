import { BadRequestException, ConflictException, ForbiddenException, Injectable, NotFoundException } from '@nestjs/common';
import { InjectDataSource, InjectRepository } from '@nestjs/typeorm';
import { DataSource, EntityManager, In, Repository } from 'typeorm';
import { AuthUser } from '../common/auth-user';
import { AuditService } from '../common/audit.service';
import { allocateFifo, distributeByShares, fromCents, OpenCharge, toCents } from '../common/money';
import { page } from '../common/pagination';
import { PeriodService } from '../common/period.service';
import { RESIDENT_ROLES } from '../common/permissions';
import { ScopeService } from '../common/scope.service';
import { CallForFunds, Payment, Resident, Unit } from '../entities';
import { CallDto, ChargeQuery, PaymentDto, PaymentQuery } from './finance.dto';

/**
 * Finance invariants (enforced here, verified by tests):
 *  I1  a charge's paid amount is DERIVED from allocations of payments whose status is 'recorded';
 *  I2  charges generated by a call sum exactly to the call total (rounding remainder on the last lot);
 *  I3  a recorded payment is never deleted — it is reversed with a reason;
 *  I4  allocated amount of a payment == payment amount, and no charge is ever over-allocated;
 *  I5  receipt numbers are unique per organization and never reused;
 *  I6  every state change is written to the audit log in the SAME transaction.
 */
const OPEN_CHARGES_SQL = `
  SELECT c.id, to_char(c.due_date, 'YYYY-MM-DD') AS "dueDate",
         (ROUND(c.amount * 100) - COALESCE(SUM(ROUND(a.amount * 100)) FILTER (WHERE p.status = 'recorded'), 0))::bigint AS "dueCents"
    FROM charges c
    LEFT JOIN allocations a ON a.charge_id = c.id
    LEFT JOIN payments p ON p.id = a.payment_id
   WHERE c.org_id = $1 AND c.unit_id = $2
   GROUP BY c.id
  HAVING (ROUND(c.amount * 100) - COALESCE(SUM(ROUND(a.amount * 100)) FILTER (WHERE p.status = 'recorded'), 0)) > 0
   ORDER BY c.due_date, c.created_at`;

const CHARGE_VIEW_SQL = `
  SELECT c.id, c.call_id AS "callId", c.residence_id AS "residenceId", c.unit_id AS "unitId", c.label,
         c.amount::float8 AS amount, to_char(c.due_date, 'YYYY-MM-DD') AS "dueDate",
         (COALESCE(SUM(ROUND(a.amount * 100)) FILTER (WHERE p.status = 'recorded'), 0) / 100.0)::float8 AS paid
    FROM charges c
    LEFT JOIN allocations a ON a.charge_id = c.id
    LEFT JOIN payments p ON p.id = a.payment_id
   WHERE c.org_id = $1 AND c.residence_id = ANY($2) AND ($3::uuid IS NULL OR c.unit_id = $3) AND ($4::uuid IS NULL OR c.call_id = $4)
     AND ($5::uuid[] IS NULL OR c.unit_id = ANY($5))
   GROUP BY c.id
   ORDER BY c.due_date DESC, c.created_at DESC`;

type ChargeRow = { id: string; callId: string; residenceId: string; unitId: string; label: string; amount: number; dueDate: string; paid: number };
const today = () => new Date().toISOString().slice(0, 10);

function withStatus(r: ChargeRow) {
  const dueCents = toCents(r.amount) - toCents(r.paid);
  const status = dueCents <= 0 ? 'paid' : toCents(r.paid) > 0 ? 'partial' : r.dueDate < today() ? 'overdue' : 'unpaid';
  return { ...r, due: fromCents(Math.max(0, dueCents)), status, overdue: dueCents > 0 && r.dueDate < today() };
}

@Injectable()
export class FinanceService {
  constructor(
    @InjectDataSource() private readonly ds: DataSource,
    @InjectRepository(CallForFunds) private readonly calls: Repository<CallForFunds>,
    @InjectRepository(Payment) private readonly payments: Repository<Payment>,
    @InjectRepository(Resident) private readonly residents: Repository<Resident>,
    private readonly scope: ScopeService,
    private readonly audit: AuditService,
    private readonly period: PeriodService,
  ) {}

  // ---- calls for funds -------------------------------------------------------------
  async listCalls(user: AuthUser, q: { limit?: number; offset?: number }) {
    const ids = await this.scope.residenceIds(user);
    if (!ids.length) return [];
    return this.calls.find({ where: { orgId: this.scope.requireOrg(user), residenceId: In(ids) }, order: { dueDate: 'DESC' }, ...page(q) });
  }

  private async ownedCall(user: AuthUser, id: string) {
    const call = await this.calls.findOneBy({ id, orgId: this.scope.requireOrg(user) });
    if (!call) throw new NotFoundException('Call for funds not found');
    await this.scope.assertResidence(user, call.residenceId);
    return call;
  }

  async createCall(user: AuthUser, dto: CallDto) {
    await this.scope.assertResidence(user, dto.residenceId);
    const call = await this.calls.save(this.calls.create({
      residenceId: dto.residenceId, orgId: this.scope.requireOrg(user), title: dto.title, period: dto.period, dueDate: dto.dueDate, basis: dto.basis,
      totalAmount: dto.basis === 'tantiemes' ? dto.totalAmount! : 0, amountPerUnit: dto.basis === 'fixed' ? dto.amountPerUnit! : 0, status: 'draft', issuedAt: null,
    }));
    await this.audit.log(user, 'create', 'calls', call.id, call.title);
    return call;
  }

  async deleteDraftCall(user: AuthUser, id: string) {
    const call = await this.ownedCall(user, id);
    if (call.status !== 'draft') throw new ConflictException('Only draft calls can be deleted');
    await this.calls.delete({ id });
    await this.audit.log(user, 'delete', 'calls', id, call.title);
  }

  /** Issue: generates one immutable charge per unit, atomically. */
  async issueCall(user: AuthUser, id: string) {
    await this.ownedCall(user, id);
    return this.ds.transaction(async (m) => {
      const [call] = await m.query('SELECT * FROM calls_for_funds WHERE id = $1 AND org_id = $2 FOR UPDATE', [id, user.orgId]);
      if (call.status !== 'draft') throw new ConflictException('Call already issued');
      const units = await m.find(Unit, { where: { residenceId: call.residence_id, orgId: user.orgId! }, order: { number: 'ASC' } });
      if (!units.length) throw new BadRequestException('The residence has no units');

      const parts = call.basis === 'fixed'
        ? units.map((u) => ({ unitId: u.id, cents: toCents(call.amount_per_unit) }))
        : distributeByShares(toCents(call.total_amount), units.map((u) => ({ unitId: u.id, tantiemes: u.tantiemes })));
      if (!parts.length) throw new BadRequestException('Units have no tantièmes to distribute on');

      for (const p of parts) {
        await m.query(
          'INSERT INTO charges (org_id, call_id, residence_id, unit_id, label, amount, due_date) VALUES ($1,$2,$3,$4,$5,$6,$7)',
          [user.orgId, id, call.residence_id, p.unitId, call.title, fromCents(p.cents), call.due_date],
        );
      }
      await m.update(CallForFunds, { id }, { status: 'issued', issuedAt: new Date() });
      await this.audit.log(user, 'issue', 'calls', id, `${call.title} — ${parts.length} charges`, m);
      return { id, status: 'issued', charges: parts.length, total: fromCents(parts.reduce((a, p) => a + p.cents, 0)) };
    });
  }

  async closeCall(user: AuthUser, id: string) {
    const call = await this.ownedCall(user, id);
    if (call.status !== 'issued') throw new ConflictException('Only issued calls can be closed');
    await this.calls.update({ id }, { status: 'closed' });
    await this.audit.log(user, 'close', 'calls', id, call.title);
    return { id, status: 'closed' };
  }

  // ---- charges -------------------------------------------------------------------------
  async listCharges(user: AuthUser, q: ChargeQuery) {
    const orgId = this.scope.requireOrg(user);
    const resident = RESIDENT_ROLES.includes(user.role);
    const unitIds = resident ? await this.scope.residentUnitIds(user) : null;
    if (resident && !unitIds!.length) return [];
    const residenceIds = await this.scope.residenceIds(user);
    if (q.unitId) await this.scope.unitFor(user, q.unitId);
    const rows: ChargeRow[] = await this.ds.query(CHARGE_VIEW_SQL, [orgId, residenceIds, q.unitId ?? null, q.callId ?? null, unitIds]);
    const views = rows.map(withStatus).filter((c) => !q.status || c.status === q.status);
    const { take, skip } = page(q);
    return views.slice(skip, skip + take);
  }

  // ---- payments ---------------------------------------------------------------------------
  async listPayments(user: AuthUser, q: PaymentQuery) {
    const orgId = this.scope.requireOrg(user);
    const where: Record<string, unknown> = { orgId };
    if (RESIDENT_ROLES.includes(user.role)) {
      const ids = await this.scope.residentUnitIds(user);
      if (!ids.length) return [];
      where.unitId = In(ids);
    } else {
      const ids = await this.scope.residenceIds(user);
      if (!ids.length) return [];
      where.residenceId = In(ids);
    }
    if (q.unitId) where.unitId = q.unitId;
    if (q.status) where.status = q.status;
    return this.payments.find({ where, order: { date: 'DESC', createdAt: 'DESC' }, ...page(q) });
  }

  private async lockedOpenCharges(m: EntityManager, orgId: string, unitId: string): Promise<OpenCharge[]> {
    // Lock the unit's charge rows so two concurrent payments for the same lot are serialized
    // and cannot both allocate the same remaining balance (I4).
    await m.query('SELECT id FROM charges WHERE org_id = $1 AND unit_id = $2 FOR UPDATE', [orgId, unitId]);
    const rows: { id: string; dueDate: string; dueCents: string }[] = await m.query(OPEN_CHARGES_SQL, [orgId, unitId]);
    return rows.map((r) => ({ id: r.id, dueDate: r.dueDate, dueCents: Number(r.dueCents) }));
  }

  private async nextReceiptNo(m: EntityManager, orgId: string): Promise<string> {
    const year = new Date().getFullYear();
    const [row] = await m.query(
      `INSERT INTO counters (org_id, name, year, value) VALUES ($1, 'receipt', $2, 1)
       ON CONFLICT (org_id, name, year) DO UPDATE SET value = counters.value + 1 RETURNING value`,
      [orgId, year],
    );
    return `REC-${year}-${String(row.value).padStart(4, '0')}`;
  }

  private async payerName(unitId: string) {
    const owner = await this.residents.findOneBy({ unitId, type: 'owner', active: true });
    return owner ? `${owner.firstName} ${owner.lastName}` : '—';
  }

  private assertNotFuture(date: string) {
    if (date > today()) throw new BadRequestException('Payment date cannot be in the future');
  }

  /** Staff: record money received. Allocated immediately (FIFO) and receipted. */
  async record(user: AuthUser, dto: PaymentDto) {
    // Residents hold payments:create only to *declare*; recording (= receipting) is a staff act.
    if (RESIDENT_ROLES.includes(user.role)) throw new ForbiddenException('Residents must declare payments instead');
    const unit = await this.scope.unitFor(user, dto.unitId);
    this.assertNotFuture(dto.date);
    const payerName = await this.payerName(unit.id);
    return this.ds.transaction(async (m) => {
      await this.period.assertOpen(unit.orgId, unit.residenceId, dto.date, m);
      const open = await this.lockedOpenCharges(m, unit.orgId, unit.id);
      const cents = toCents(dto.amount);
      const due = open.reduce((a, c) => a + c.dueCents, 0);
      if (!open.length) throw new ConflictException('Nothing is due for this unit');
      if (cents > due) throw new ConflictException(`Amount exceeds the balance due (${fromCents(due)})`);
      const { allocations } = allocateFifo(cents, open);
      const receiptNo = await this.nextReceiptNo(m, unit.orgId);
      const payment = await m.save(Payment, m.create(Payment, {
        orgId: unit.orgId, residenceId: unit.residenceId, unitId: unit.id, payerName, amount: dto.amount, date: dto.date, method: dto.method,
        reference: dto.reference, note: dto.note, status: 'recorded', verified: false, receiptNo, declaredBy: null, createdBy: user.id, confirmedBy: user.id,
        reason: null, reversedAt: null,
      }));
      for (const a of allocations) {
        await m.query('INSERT INTO allocations (org_id, payment_id, charge_id, amount) VALUES ($1,$2,$3,$4)', [unit.orgId, payment.id, a.chargeId, fromCents(a.cents)]);
      }
      await this.audit.log(user, 'create', 'payments', payment.id, `${receiptNo} — ${dto.amount}`, m);
      return { ...payment, allocations: allocations.map((a) => ({ chargeId: a.chargeId, amount: fromCents(a.cents) })) };
    });
  }

  /** Resident: declare a payment made elsewhere. Pending; has NO financial effect until validated. */
  async declare(user: AuthUser, dto: PaymentDto) {
    if (!RESIDENT_ROLES.includes(user.role)) throw new ForbiddenException('Only residents declare payments; staff record them');
    const unit = await this.scope.unitFor(user, dto.unitId);
    this.assertNotFuture(dto.date);
    if (!dto.reference) throw new BadRequestException('A reference is required to declare a payment');
    await this.period.assertOpen(unit.orgId, unit.residenceId, dto.date);
    const open: { dueCents: string }[] = await this.ds.query(OPEN_CHARGES_SQL, [unit.orgId, unit.id]);
    const due = open.reduce((a, r) => a + Number(r.dueCents), 0);
    if (toCents(dto.amount) > due) throw new ConflictException(`Amount exceeds the balance due (${fromCents(due)})`);
    const payment = await this.payments.save(this.payments.create({
      orgId: unit.orgId, residenceId: unit.residenceId, unitId: unit.id, payerName: user.name, amount: dto.amount, date: dto.date, method: dto.method,
      reference: dto.reference, note: dto.note, status: 'pending', verified: false, receiptNo: null, declaredBy: user.id, createdBy: user.id, confirmedBy: null, reason: null, reversedAt: null,
    }));
    await this.audit.log(user, 'declare', 'payments', payment.id, `${user.name} — ${dto.amount}`);
    return payment;
  }

  private async ownedPayment(user: AuthUser, id: string) {
    const p = await this.payments.findOneBy({ id, orgId: this.scope.requireOrg(user) });
    if (!p) throw new NotFoundException('Payment not found');
    await this.scope.assertResidence(user, p.residenceId);
    return p;
  }

  async confirm(user: AuthUser, id: string) {
    await this.ownedPayment(user, id);
    return this.ds.transaction(async (m) => {
      const [p] = await m.query('SELECT * FROM payments WHERE id = $1 AND org_id = $2 FOR UPDATE', [id, user.orgId]);
      if (p.status !== 'pending') throw new ConflictException('Only pending payments can be confirmed');
      await this.period.assertOpen(user.orgId!, p.residence_id, p.date, m);
      const open = await this.lockedOpenCharges(m, user.orgId!, p.unit_id);
      const cents = toCents(p.amount);
      const due = open.reduce((a, c) => a + c.dueCents, 0);
      if (cents > due) throw new ConflictException(`The balance due is now lower than this payment (${fromCents(due)})`);
      const { allocations } = allocateFifo(cents, open);
      const receiptNo = await this.nextReceiptNo(m, user.orgId!);
      await m.update(Payment, { id }, { status: 'recorded', receiptNo, confirmedBy: user.id });
      for (const a of allocations) {
        await m.query('INSERT INTO allocations (org_id, payment_id, charge_id, amount) VALUES ($1,$2,$3,$4)', [user.orgId, id, a.chargeId, fromCents(a.cents)]);
      }
      await this.audit.log(user, 'confirm', 'payments', id, receiptNo, m);
      return { id, status: 'recorded', receiptNo };
    });
  }

  async reject(user: AuthUser, id: string, reason: string) {
    const p = await this.ownedPayment(user, id);
    if (p.status !== 'pending') throw new ConflictException('Only pending payments can be rejected');
    await this.payments.update({ id }, { status: 'rejected', reason });
    await this.audit.log(user, 'reject', 'payments', id, reason);
    return { id, status: 'rejected' };
  }

  /** Reversal keeps the payment, its receipt and its allocations; the charge simply becomes due again (I1, I3). */
  async reverse(user: AuthUser, id: string, reason: string) {
    await this.ownedPayment(user, id);
    return this.ds.transaction(async (m) => {
      const [p] = await m.query('SELECT status, receipt_no, verified, date, residence_id FROM payments WHERE id = $1 AND org_id = $2 FOR UPDATE', [id, user.orgId]);
      if (p.status !== 'recorded') throw new ConflictException('Only recorded payments can be reversed');
      // A payment confirmed by the bank statement is evidence, not a mere entry: un-match it explicitly first.
      if (p.verified) throw new ConflictException('This payment is bank-verified; unmatch it from the bank statement before reversing');
      await this.period.assertOpen(user.orgId!, p.residence_id, p.date, m);
      await m.update(Payment, { id }, { status: 'reversed', reason, reversedAt: new Date() });
      await this.audit.log(user, 'reverse', 'payments', id, `${p.receipt_no}: ${reason}`, m);
      return { id, status: 'reversed' };
    });
  }

  // ---- statements & summary ------------------------------------------------------------------
  async statement(user: AuthUser, unitId: string) {
    const unit = await this.scope.unitFor(user, unitId);
    const charges = await this.ds.query(`SELECT to_char(due_date,'YYYY-MM-DD') AS date, label, amount::float8 AS debit FROM charges WHERE org_id=$1 AND unit_id=$2`, [unit.orgId, unit.id]);
    const pays = await this.ds.query(`SELECT to_char(date,'YYYY-MM-DD') AS date, method AS label, amount::float8 AS credit, receipt_no AS ref FROM payments WHERE org_id=$1 AND unit_id=$2 AND status='recorded'`, [unit.orgId, unit.id]);
    const lines = [
      ...charges.map((c: { date: string; label: string; debit: number }) => ({ kind: 'charge', date: c.date, label: c.label, debitCents: toCents(c.debit), creditCents: 0, ref: '' })),
      ...pays.map((p: { date: string; label: string; credit: number; ref: string }) => ({ kind: 'payment', date: p.date, label: p.label, debitCents: 0, creditCents: toCents(p.credit), ref: p.ref })),
    ].sort((a, b) => a.date.localeCompare(b.date) || (a.kind === 'charge' ? -1 : 1));
    let balance = 0;
    const out = lines.map((l) => {
      balance += l.debitCents - l.creditCents;
      return { kind: l.kind, date: l.date, label: l.label, debit: fromCents(l.debitCents), credit: fromCents(l.creditCents), ref: l.ref, balance: fromCents(balance) };
    });
    return { unitId: unit.id, balance: fromCents(balance), lines: out };
  }

  async summary(user: AuthUser, residenceId?: string) {
    const orgId = this.scope.requireOrg(user);
    const all = await this.scope.residenceIds(user);
    if (residenceId && !all.includes(residenceId)) throw new NotFoundException('Residence not found');
    const ids = residenceId ? [residenceId] : all;
    const rows: ChargeRow[] = ids.length ? await this.ds.query(CHARGE_VIEW_SQL, [orgId, ids, null, null, null]) : [];
    const views = rows.map(withStatus);
    const charged = views.reduce((a, c) => a + toCents(c.amount), 0);
    const collected = views.reduce((a, c) => a + toCents(c.paid), 0);
    const overdue = views.filter((c) => c.overdue).reduce((a, c) => a + toCents(c.due), 0);
    const [exp] = ids.length ? await this.ds.query(`SELECT COALESCE(SUM(ROUND(amount*100)),0)::bigint AS cents FROM expenses WHERE org_id=$1 AND residence_id = ANY($2) AND status='paid'`, [orgId, ids]) : [{ cents: 0 }];
    return {
      charged: fromCents(charged), collected: fromCents(collected), outstanding: fromCents(charged - collected), overdue: fromCents(overdue),
      expensesPaid: fromCents(Number(exp.cents)), collectionRate: charged ? collected / charged : 0,
    };
  }
}
